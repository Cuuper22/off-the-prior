"""Gradient search through Timestral.

(a) `grad_search`: generator-parameter space. Several random starts, each a genome whose four
    slots use components that `torch_gen` can differentiate. Per step, per start, `n_draws`
    fixed-noise series are generated by `TorchMixture`, forecast by `otp.model.forecast_torch`,
    and the loss is

        -( mean_b [ log pinball(Timestral) - log pinball(oracle) ] ) + penalty

    where pinball is the mean quantile loss over horizon and levels on the generator's own
    realized future, and the oracle quantiles come from `K` Monte Carlo continuations of the same
    differentiable generator from the same end-of-context state. The log ratio is used (instead of
    the raw difference) because it is scale free and matches the ratio the other methods
    maximize; the naive-scale divisor of sCRPS cancels in it.
    Feasibility is the same rule as `objective.py` (geometric mean over draws of
    pinball(oracle) / pinball(seasonal naive) at most 0.8, finite, context std in range). It is
    checked after every step on the new genes with generator-only passes (no Timestral calls): a
    step that would leave the feasible region is shortened (1, 1/2, 1/4, 1/8 of the Adam step) and,
    if none is feasible, rejected and the start's learning rate is halved. A small hinge penalty near
    the boundary keeps the gradient pointing inward.
    Genes live in the genome box [0, 1] (projected after each step); only the genes
    `torch_gen.gene_bounds` marks as free move.
    At fixed fractions of the run the current genes of every start are scored with the standard
    non-differentiable pipeline (`Evaluator.evaluate`), so the history is on the same metric as the
    other methods.

    Call counting convention: one series passed through `forecast_torch` forward AND backward
    counts as 2 Timestral calls (symmetric averaging inside it is part of the same pass); the
    standard-pipeline scoring counts 3 calls per genome as everywhere else.

(b) `input_sensitivity`: for an in-prior series, the smallest L2 perturbation of the context (as
    a fraction of the context std per step) found by projected gradient ascent that doubles
    Timestral's MASE on the fixed realized future. This is a sensitivity measure on the model,
    not a generator failure (the oracle is unaffected by what happens to the observed context).
"""

from __future__ import annotations

import csv
import math
import os

import numpy as np
import torch

from otp.model import MEDIAN_INDEX, default_device, forecast_torch
from otp.search import torch_gen as tg
from otp.search.objective import ORC_SN_MAX, STD_HI, STD_LO

FEAS_MARGIN = 0.02      # hinge penalty starts this far (in log ratio) before the boundary
PENALTY_WEIGHT = 10.0


def feasibility_terms(gen: tg.TorchMixture, g: torch.Tensor, tau: float, period: int):
    """Generator-only pass: context, futures, and the quantities the feasibility rule needs."""
    ctx, fut = gen.forward(g, tau)
    y = fut[:, 0]
    q_orc = tg.oracle_quantiles(fut)
    q_sn = tg.seasonal_naive_quantiles(ctx, gen.H, period)
    lo = tg.pinball(y, q_orc)
    lsn = tg.pinball(y, q_sn)
    return ctx, y, q_orc, lo, lsn


def is_feasible(ctx, lo, lsn) -> bool:
    if not (torch.isfinite(ctx).all() and torch.isfinite(lo).all() and torch.isfinite(lsn).all()):
        return False
    if (lo <= 0).any() or (lsn <= 0).any():
        return False
    s = ctx.std(dim=-1, unbiased=False)
    if not ((s >= STD_LO).all() and (s <= STD_HI).all()):
        return False
    return bool(torch.log(lo / lsn).mean() <= math.log(ORC_SN_MAX))


def feasible_at(gen, g_np: np.ndarray, tau: float, period: int, dev) -> bool:
    with torch.no_grad():
        ctx, _, _, lo, lsn = feasibility_terms(gen, torch.tensor(g_np, dtype=torch.float64, device=dev), tau, period)
    return is_feasible(ctx, lo, lsn)


def _tau(step: int, n_steps: int, tau0: float = 8.0, tau1: float = 1.0) -> float:
    return max(tau1, tau0 * (1.0 - step / max(1, n_steps)))


def plan_steps(budget: int, n_restarts: int, n_draws: int, n_events: int, n_seeds: int = 3) -> int:
    """Number of gradient steps that fit the budget together with `n_events` scoring rounds."""
    return max(0, (budget - n_events * n_restarts * n_seeds) // (2 * n_restarts * n_draws))


def grad_search(ev, seed: int, size: str = "5M", n_restarts: int = 3, n_draws: int = 2, K: int = 64,
                lr: float = 0.03, n_events: int = 5, max_screen: int = 400, log=print):
    """Run the gradient search under the budget of `ev` (an `objective.Evaluator`)."""
    dev = default_device()
    rng = np.random.default_rng(seed)
    n_steps = plan_steps(ev.budget, n_restarts, n_draws, n_events, ev.n_seeds)
    score_at = sorted({int(round(n_steps * k / (n_events - 1))) for k in range(n_events)})
    # starts: random restricted genomes that are feasible on the differentiable generator (no Timestral calls)
    starts, screened = [], 0
    while len(starts) < n_restarts and screened < max_screen:
        screened += 1
        g = tg.restricted_genome(rng)
        gen = tg.TorchMixture(g, B=n_draws, K=K, seed=int(rng.integers(2**31)), device=dev)
        per = tg.period_of(g)
        if feasible_at(gen, g, _tau(0, n_steps), per, dev):
            starts.append({"g": g, "gen": gen, "per": per, "lo": tg.gene_bounds(g)[0], "hi": tg.gene_bounds(g)[1],
                           "free": tg.gene_bounds(g)[2], "m": np.zeros_like(g), "v": np.zeros_like(g),
                           "lr": lr, "t": 0, "rejected": 0})
    log(f"gradient search seed {seed}: {len(starts)} starts after screening {screened} draws, {n_steps} steps, "
        f"scoring at steps {score_at}")
    trace_path = os.path.join(ev.run_dir, "grad_trace.csv")
    trace = []
    step = 0
    while True:
        if step in score_at:
            ev.evaluate([s["g"] for s in starts], origin=f"grad_step{step}")
            log(f"  step {step}: calls {ev.calls}/{ev.budget}, best fitness so far {ev.best:.3f}")
        if step >= n_steps or ev.remaining < 2 * len(starts) * n_draws:
            break
        tau = _tau(step, n_steps)
        gts = [torch.tensor(s["g"], dtype=torch.float64, device=dev, requires_grad=True) for s in starts]
        terms = [feasibility_terms(s["gen"], gt, tau, s["per"]) for s, gt in zip(starts, gts)]
        ctx_all = torch.cat([t[0] for t in terms], 0)
        q_ts = forecast_torch(size, ctx_all.float(), starts[0]["gen"].H).to(torch.float64)
        loss_total, stats = 0.0, []
        for r, (s, gt, (ctx, y, q_orc, lo, lsn)) in enumerate(zip(starts, gts, terms)):
            qt = q_ts[r * n_draws:(r + 1) * n_draws]
            lt = tg.pinball(y, qt)
            log_gap = (torch.log(lt) - torch.log(lo)).mean()
            viol = torch.relu(torch.log(lo / lsn).mean() - math.log(ORC_SN_MAX) + FEAS_MARGIN)
            loss = -log_gap + PENALTY_WEIGHT * viol
            ok = bool(torch.isfinite(loss))
            loss_total = loss_total + (loss if ok else 0.0)
            stats.append((ok, float(log_gap.detach()) if ok else float("nan"), float(viol.detach()) if ok else float("nan"),
                          is_feasible(ctx, lo, lsn)))
        if torch.is_tensor(loss_total):
            loss_total.backward()
        ev.charge(2 * len(starts) * n_draws)
        for r, (s, gt) in enumerate(zip(starts, gts)):
            ok, log_gap, viol, feas = stats[r]
            nback = -1
            if ok and gt.grad is not None and torch.isfinite(gt.grad).all():
                grad = gt.grad.cpu().numpy() * s["free"]
                s["t"] += 1
                s["m"] = 0.9 * s["m"] + 0.1 * grad
                s["v"] = 0.999 * s["v"] + 0.001 * grad ** 2
                mh, vh = s["m"] / (1 - 0.9 ** s["t"]), s["v"] / (1 - 0.999 ** s["t"])
                direction = s["lr"] * mh / (np.sqrt(vh) + 1e-8)
                for nback, alpha in enumerate((1.0, 0.5, 0.25, 0.125)):
                    cand = np.clip(s["g"] - alpha * direction, s["lo"], s["hi"])
                    if feasible_at(s["gen"], cand, _tau(step + 1, n_steps), s["per"], dev):
                        s["g"] = cand
                        break
                else:
                    nback = 4
                    s["rejected"] += 1
                    s["lr"] *= 0.5
            trace.append({"step": step, "restart": r, "calls": ev.calls, "tau": tau, "log_pinball_gap": log_gap,
                          "violation": viol, "feasible_before": feas, "backtracks": nback, "lr": s["lr"]})
        step += 1
    with open(trace_path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(trace[0].keys()) if trace else ["step"])
        w.writeheader()
        w.writerows(trace)
    return {"n_steps": n_steps, "screened": screened, "starts": len(starts),
            "rejected_steps": [s["rejected"] for s in starts]}


# ---------------------------------------------------------------- (b) input-space sensitivity
def _mase_fn(size: str, y: torch.Tensor, scale: float, H: int):
    def f(x):
        q = forecast_torch(size, x[None], H)[0]
        return (y - q[:, MEDIAN_INDEX]).abs().mean() / scale
    return f


def _pgd(f, x, radius: float, n_iter: int, rng):
    """Maximize f(x + d) over ||d||_2 <= radius with normalized-gradient steps. Returns best value and its d."""
    d = torch.randn_like(x) * 1e-3
    d = d * (radius / d.norm()) * 0.01
    best, best_d = -1.0, d.clone()
    for k in range(n_iter):
        d.requires_grad_(True)
        val = f(x + d)
        val.backward()
        v = float(val)
        if v > best:
            best, best_d = v, d.detach().clone()
        g = d.grad
        gn = g.norm()
        with torch.no_grad():
            if not torch.isfinite(gn) or gn == 0:
                break
            eta = radius * (0.5 * (1 - k / n_iter) + 0.05)
            d = d.detach() + eta * g / gn
            n = d.norm()
            if n > radius:
                d = d * (radius / n)
    with torch.no_grad():
        v = float(f(x + d.detach()))
    if v > best:
        best, best_d = v, d.detach().clone()
    return best, best_d


def input_sensitivity(size: str, series_seed: int, T: int = 2048, H: int = 128, factor: float = 2.0,
                      n_iter: int = 25, grid=None, n_bisect: int = 5):
    """Smallest relative perturbation that raises Timestral's MASE by `factor` on an in-prior series.

    Radius is expressed as rho = ||d||_2 / (std(context) * sqrt(T)), the per-step RMS of the
    perturbation as a fraction of the context std. Returns a dict with rho, ||d||_2 / std, clean and
    perturbed MASE, and the number of forward+backward passes used.
    """
    from otp.generators.base import make_sample
    from otp.generators.primitives import in_prior
    from otp import metrics

    dev = default_device()
    s = make_sample(in_prior(series_seed), T, H, seed=series_seed, n_paths=2)
    x = torch.tensor(s.context[0], dtype=torch.float32, device=dev)
    y = torch.tensor(s.future[0], dtype=torch.float32, device=dev)
    scale = float(metrics.naive_scale(s.context, s.period)[0])
    sd = float(x.std())
    f = _mase_fn(size, y, scale, H)
    rng = np.random.default_rng(series_seed)
    with torch.no_grad():
        m0 = float(f(x))
    passes = 0
    grid = grid or [10 ** (-3 + k / 3) for k in range(10)]
    hit, prev, best_at = None, 0.0, {}
    for rho in grid:
        val, _ = _pgd(f, x, rho * sd * math.sqrt(T), n_iter, rng)
        passes += n_iter
        best_at[rho] = val
        if val >= factor * m0:
            hit = rho
            break
        prev = rho
    if hit is None:
        return {"size": size, "series_seed": series_seed, "period": s.period, "mase_clean": m0, "reached": False,
                "rho": float("nan"), "l2_over_std": float("nan"), "mase_perturbed": best_at[grid[-1]],
                "rho_max_tried": grid[-1], "passes": passes}
    lo, hi, val_hi = max(prev, 1e-6), hit, best_at[hit]
    for _ in range(n_bisect):
        mid = math.sqrt(lo * hi)
        val, _ = _pgd(f, x, mid * sd * math.sqrt(T), n_iter, rng)
        passes += n_iter
        if val >= factor * m0:
            hi, val_hi = mid, val
        else:
            lo = mid
    return {"size": size, "series_seed": series_seed, "period": s.period, "mase_clean": m0, "reached": True,
            "rho": hi, "l2_over_std": hi * math.sqrt(T), "mase_perturbed": val_hi, "rho_max_tried": grid[-1],
            "passes": passes}
